// Use while para contar de 10 até 0 no console. Mostre uma mensagem no fim: "Contagem finalizada!".

console.log("=-".repeat(10));
console.log("Contagem regressiva");
console.log("=-".repeat(10));

let numero = 10;

while (numero >= 0) {
  console.log(numero);
  numero--;
}
console.log("=-".repeat(10));
console.log("Contagem finalizada");
console.log("=-".repeat(10));
